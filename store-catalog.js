(() => {
    "use strict";

    const catalog = window.GA_STORE_CATALOG || [];
    let activeCategory = "all";
    let searchText = "";

    const labels = {
        all: "ALL ITEMS",
        profile: "PROFILE",
        collectibles: "COLLECTIBLES",
        vehicles: "VEHICLES",
        property: "PROPERTY",
        casino: "CASINO COSMETICS",
        lounge: "CLUB & LOUNGE",
        trophies: "TROPHIES",
        prestige: "PRESTIGE"
    };

    function money(value) {
        return `${Number(value || 0).toLocaleString("en-US")} AC`;
    }

    function escapeHtml(value) {
        return String(value)
            .replaceAll("&", "&amp;")
            .replaceAll("<", "&lt;")
            .replaceAll(">", "&gt;")
            .replaceAll('"', "&quot;")
            .replaceAll("'", "&#039;");
    }

    function filteredCatalog() {
        const q = searchText.trim().toLowerCase();

        return catalog.filter(item => {
            const matchesCategory =
                activeCategory === "all" ||
                item.storeCategory === activeCategory;

            const haystack =
                `${item.name} ${item.tag} ${item.desc}`.toLowerCase();

            const matchesSearch =
                !q || haystack.includes(q);

            return matchesCategory && matchesSearch;
        });
    }

    function render() {
        const grid = document.getElementById("gaStoreGrid");
        const count = document.getElementById("gaStoreCount");
        if (!grid) return;

        const items = filteredCatalog();

        if (count) {
            count.textContent =
                `${items.length} ITEM${items.length === 1 ? "" : "S"} SHOWN`;
        }

        if (!items.length) {
            grid.innerHTML = `
                <div class="ga-store-empty">
                    No store items match this filter.
                </div>
            `;
            return;
        }

        grid.innerHTML = items.map(item => `
            <article
                class="ga-store-card"
                data-store-category="${escapeHtml(item.storeCategory)}"
            >
                <div class="ga-store-card-top">
                    <span class="ga-store-tag">${escapeHtml(item.tag)}</span>
                    <span class="ga-store-category">
                        ${escapeHtml(labels[item.storeCategory] || item.storeCategory)}
                    </span>
                </div>

                <h3>${escapeHtml(item.name)}</h3>

                <p>${escapeHtml(item.desc)}</p>

                <div class="ga-store-card-bottom">
                    <div class="ga-store-price">${money(item.price)}</div>

                    <button
                        type="button"
                        class="ga-store-buy"
                        onclick="buyItem('${escapeHtml(item.name)}', ${Number(item.price)})"
                    >
                        PURCHASE
                    </button>
                </div>
            </article>
        `).join("");

        if (typeof window.updateStoreButtons === "function") {
            window.updateStoreButtons();
        }
    }

    function setCategory(category, button) {
        activeCategory = category;

        document
            .querySelectorAll(".ga-store-filter")
            .forEach(el => el.classList.remove("active"));

        button?.classList.add("active");
        render();
    }

    function bind() {
        document
            .querySelectorAll(".ga-store-filter")
            .forEach(button => {
                button.addEventListener("click", () => {
                    setCategory(
                        button.dataset.category || "all",
                        button
                    );
                });
            });

        const search = document.getElementById("gaStoreSearch");

        search?.addEventListener("input", () => {
            searchText = search.value || "";
            render();
        });

        render();
    }

    window.gaStoreSetCategory = setCategory;
    window.gaRenderStore = render;

    if (document.readyState === "loading") {
        document.addEventListener("DOMContentLoaded", bind, { once: true });
    } else {
        bind();
    }
})();
